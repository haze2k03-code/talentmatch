"""Generates db/seed.sql with fictional clients, roles and pipeline rows.

All names and companies are made up. Re-run with:  python scripts/generate_seed.py
The random seed is fixed, so the output is the same every time.
"""
import random
from pathlib import Path

random.seed(42)

LEVELS = {
    1: "Senior Software Engineer",
    2: "Staff Engineer",
    3: "Engineering Manager",
    4: "Senior Engineering Manager",
    5: "Director of Engineering",
    6: "VP of Engineering",
}

# Each track has a core skill set and the titles used at each level.
TRACKS = {
    "platform": {
        "skills": ["aws", "kubernetes", "terraform", "go", "ci/cd", "observability", "linux", "gcp"],
        "titles": {1: "Senior Platform Engineer", 2: "Staff Platform Engineer", 3: "Manager, Cloud Platform",
                   4: "Senior Manager, Infrastructure", 5: "Director, Platform Engineering", 6: "VP, Infrastructure"},
    },
    "data": {
        "skills": ["python", "sql", "spark", "airflow", "snowflake", "dbt", "kafka", "ml"],
        "titles": {1: "Senior Data Engineer", 2: "Staff Data Engineer", 3: "Manager, Data Engineering",
                   4: "Senior Manager, Data Platform", 5: "Director of Data", 6: "VP, Data & Analytics"},
    },
    "backend": {
        "skills": ["java", "python", "microservices", "postgresql", "aws", "system design", "kafka", "go"],
        "titles": {1: "Senior Backend Engineer", 2: "Staff Software Engineer", 3: "Engineering Manager",
                   4: "Senior Engineering Manager", 5: "Director of Engineering", 6: "VP of Engineering"},
    },
    "product": {
        "skills": ["roadmapping", "sql", "experimentation", "b2b saas", "stakeholder management", "analytics", "pricing", "ai products"],
        "titles": {1: "Senior Product Manager", 2: "Principal Product Manager", 3: "Group Product Manager",
                   4: "Senior Group Product Manager", 5: "Director of Product", 6: "VP of Product"},
    },
    "security": {
        "skills": ["cloud security", "iam", "soc 2", "threat modeling", "aws", "incident response", "zero trust", "python"],
        "titles": {1: "Senior Security Engineer", 2: "Staff Security Engineer", 3: "Manager, Security Engineering",
                   4: "Senior Manager, Security", 5: "Director of Security", 6: "CISO"},
    },
}
LEADERSHIP_SKILLS = ["people management", "hiring", "budgeting", "org design"]

DOMAINS = ["fintech", "healthcare", "saas", "e-commerce", "logistics"]
LOCATIONS = ["Seattle, WA", "Austin, TX", "New York, NY", "Chicago, IL", "Denver, CO", "San Francisco, CA"]
OWNERS = ["Aarav M.", "Meera K.", "Kabir S."]

FIRST = ["Daniel", "Priya", "Marcus", "Elena", "Rahul", "Sofia", "Owen", "Nadia", "Victor", "Hannah",
         "Arjun", "Grace", "Leo", "Maya", "Ethan", "Zara", "Caleb", "Irene", "Samuel", "Tara"]
LAST = ["Hartwell", "Venkat", "Okafor", "Brennan", "Iyer", "Lindqvist", "Marlow", "Qureshi", "Delgado",
        "Fenwick", "Raman", "Ashby", "Novak", "Castell", "Whitmore", "Kaplan", "Osei", "Varga", "Pruitt", "Moreau"]
COMPANIES = ["Northwind Cloud", "Brightpath Health", "Quarry Labs", "Ledgerline", "Tidewater Logistics",
             "Pinecrest Analytics", "Orbitly", "Harborview Systems", "Cobalt Retail", "Meridian Pay",
             "Stackfield", "Lumen Bio", "Vantage Freight", "Copperleaf Software"]

# Pay bands by level, USD thousands (base pay)
PAY = {1: (165, 210), 2: (195, 245), 3: (190, 240), 4: (220, 275), 5: (250, 320), 6: (300, 400)}


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def arr(items) -> str:
    return "ARRAY[" + ", ".join(q(i) for i in items) + "]::TEXT[]" if items else "'{}'::TEXT[]"


def pick_skills(track: str, level: int, n: int):
    skills = random.sample(TRACKS[track]["skills"], n)
    if level >= 3:
        skills += random.sample(LEADERSHIP_SKILLS, 2 if level >= 5 else 1)
    return skills


lines = ["-- Generated by scripts/generate_seed.py. All people and companies are fictional.",
         "TRUNCATE pipeline, roles, clients RESTART IDENTITY CASCADE;", ""]

# ---- clients ----
clients = []
names = random.sample([f"{f} {l}" for f in FIRST for l in LAST], 18)
for i, name in enumerate(names):
    track = list(TRACKS)[i % len(TRACKS)]
    level = random.choice([2, 3, 3, 4, 4, 5, 5, 6])
    lo, hi = PAY[level]
    current = random.randint(lo - 15, hi - 25)
    expected = current + random.choice([10, 15, 20, 25, 35])
    c = dict(
        name=name,
        title=TRACKS[track]["titles"][level],
        company=random.choice(COMPANIES),
        level=level,
        years=6 + level * 2 + random.randint(0, 4),
        current=current,
        expected=expected,
        skills=pick_skills(track, level, random.randint(5, 7)),
        domain=random.choice(DOMAINS),
        location=random.choice(LOCATIONS),
        remote=random.random() < 0.75,
        owner=OWNERS[i % len(OWNERS)],
        joined=f"2026-{random.randint(6, 10):02d}-{random.randint(1, 28):02d}",
    )
    clients.append(c)
    lines.append(
        "INSERT INTO clients (name, current_title, current_company, seniority, years_exp, current_pay_k, "
        "expected_pay_k, skills, domain, location, open_to_remote, owner, joined_on) VALUES ("
        f"{q(c['name'])}, {q(c['title'])}, {q(c['company'])}, {c['level']}, {c['years']}, {c['current']}, "
        f"{c['expected']}, {arr(c['skills'])}, {q(c['domain'])}, {q(c['location'])}, "
        f"{'TRUE' if c['remote'] else 'FALSE'}, {q(c['owner'])}, DATE {q(c['joined'])});"
    )

lines.append("")

# ---- roles ----
for i in range(36):
    track = list(TRACKS)[i % len(TRACKS)]
    level = random.choice([2, 3, 3, 4, 4, 5, 5, 6])
    lo, hi = PAY[level]
    pay_min = random.randint(lo - 10, lo + 15)
    pay_max = pay_min + random.randint(30, 60)
    pool = TRACKS[track]["skills"]
    required = random.sample(pool, 4)
    if level >= 3:
        required.append(random.choice(LEADERSHIP_SKILLS))
    nice = random.sample([s for s in pool if s not in required], 2)
    lines.append(
        "INSERT INTO roles (company, title, seniority, pay_min_k, pay_max_k, required_skills, nice_skills, "
        "domain, location, remote, is_open, posted_on) VALUES ("
        f"{q(random.choice(COMPANIES))}, {q(TRACKS[track]['titles'][level])}, {level}, {pay_min}, {pay_max}, "
        f"{arr(required)}, {arr(nice)}, {q(random.choice(DOMAINS))}, {q(random.choice(LOCATIONS))}, "
        f"{'TRUE' if random.random() < 0.5 else 'FALSE'}, {'TRUE' if i < 33 else 'FALSE'}, "
        f"DATE '2026-{random.randint(9, 10):02d}-{random.randint(1, 28):02d}');"
    )

lines.append("")

# ---- pipeline: put each client's best few matches into different stages ----
# Uses the match_scores view, so run matching.sql before this file.
lines.append("""-- Seed the pipeline from each client's top matches, spread across stages.
INSERT INTO pipeline (client_id, role_id, stage, updated_at)
SELECT client_id, role_id,
       (ARRAY['offer','interview','outreach','applied','shortlisted','rejected']::pipeline_stage[])
         [1 + ((client_id * 7 + rnk * 3) % 6)],
       NOW() - ((client_id * 13 + rnk * 5) % 20) * INTERVAL '1 day'
FROM (
  SELECT client_id, role_id,
         ROW_NUMBER() OVER (PARTITION BY client_id ORDER BY score DESC, role_id) AS rnk
  FROM match_scores
) ranked
WHERE rnk <= 3 AND client_id % 6 <> 0;   -- every 6th client has no pipeline yet (needs attention)
""")

out = Path(__file__).resolve().parent.parent / "db" / "seed.sql"
out.write_text("\n".join(lines) + "\n")
print(f"Wrote {out}")
